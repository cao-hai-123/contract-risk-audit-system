export function contractProfiles(contract) {
  // A reference to another sector deep in a contract does not change this contract's type.
  const title = String(contract?.sourceFile || contract?.fileName || '')
  const text = title + '\n' + (contract?.paragraphStructure || contract?.paragraphs || []).slice(0, 25)
    .map((p) => p.content || p.text || '').join('\n').slice(0, 6500)
  const profiles = Object.entries(profilePatterns).filter(([, pattern]) => pattern.test(text)).map(([key]) => key)
  return new Set(profiles)
}

export function appliesToProfiles(profiles, contract) {
  if (!profiles?.length) return true
  const actual = contractProfiles(contract)
  return profiles.some((profile) => actual.has(profile))
}

const requirement = (label, pattern) => ({ label, pattern })
